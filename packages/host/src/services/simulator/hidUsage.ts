/** HID usage page for keyboard keys. */
export const HID_PAGE_KEYBOARD = 0x07;

/** HID usage page for consumer controls (Home, Power, volume). */
export const HID_PAGE_CONSUMER = 0x0c;

/** Consumer usages for the hardware buttons Argus exposes. */
export const HID_CONSUMER_USAGE: Record<string, number> = {
  ios_home: 0x40,
  ios_power: 0x30,
};

/**
 * NSEvent modifier flag -> HID usage for the matching left-hand modifier key.
 * The guest tracks modifiers as ordinary key presses, so a chord is sent as
 * modifier-down, key, modifier-up rather than as a flags field.
 */
const MODIFIER_USAGES: readonly [number, number][] = [
  [1 << 17, 0xe1], // shift    -> Left Shift
  [1 << 18, 0xe0], // control  -> Left Control
  [1 << 19, 0xe2], // option   -> Left Alt
  [1 << 20, 0xe3], // command  -> Left GUI
];

/** HID usages for every modifier set in an NSEvent modifier mask. */
export function modifierUsages(modifierFlags: number): number[] {
  return MODIFIER_USAGES.filter(([flag]) => (modifierFlags & flag) !== 0).map(
    ([, usage]) => usage,
  );
}

/**
 * Translate a macOS virtual key code to its HID keyboard usage, or null when
 * the key has no mapping.
 */
export function hidUsageForKeyCode(keyCode: number): number | null {
  const usage = HID_USAGE_BY_KEY_CODE[keyCode];

  return usage ? usage : null;
}
