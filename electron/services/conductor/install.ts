/**
 * Shared conductor install primitives — the shim source and the npm-install
 * argument list, used by BOTH the build-time installer
 * (`scripts/prepare-conductor.ts`, which bundles conductor into the app) and
 * the runtime provisioner (`override.ts`, which installs a user-selected
 * version into `~/.argus/conductor/<version>/` without an app update).
 *
 * Deliberately leaf-level: only `node:` imports, no electron/app/logger, so
 * the tsx-run build script can import it without dragging in Electron.
 */

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

export const CONDUCTOR_PACKAGE = "@houwert/conductor";

/** Marker file (next to `bin/`) recording which version an install tree holds. */
export const VERSION_MARKER = ".version";

/**
 * The conductor shim. Resolves the real entry point via `__dirname`-relative
 * lookup, so the same shim works in `native/conductor/bin/` (dev),
 * `<resourcesPath>/conductor/bin/` (packaged), and
 * `~/.argus/conductor/<version>/bin/` (runtime override) without rewriting.
 *
 * It intercepts `--device ios|web` placeholders and POSTs to the Argus MCP
 * resolver to acquire a runtime on demand. See `cli/conductor.ts` for the
 * full story.
 */
export const SHIM_SCRIPT = `#!/usr/bin/env node
/* eslint-disable */
// Auto-generated by scripts/prepare-conductor.ts. Do not edit manually.
'use strict';

const path = require('path');
const { spawn } = require('child_process');
const http = require('http');

const CONDUCTOR_ENTRY = path.join(
  __dirname,
  '..',
  'node_modules',
  '@houwert',
  'conductor',
  'dist',
  'index.js',
);

function findDeviceFlag(argv) {
  for (let i = 0; i < argv.length - 1; i++) {
    if (argv[i] === '--device') {
      return { index: i + 1, value: argv[i + 1] };
    }
  }
  return null;
}

function classifyDevice(value) {
  if (!value) return null;
  if (value === 'web' || value === 'web:chromium') return 'web';
  if (value === 'ios') return 'ios';
  return null; // Already a concrete device ID — pass through.
}

function resolveDevice(platform) {
  const url = process.env.ARGUS_RESOLVER_URL;
  const agentId = process.env.ARGUS_AGENT_ID;
  const token = process.env.ARGUS_RESOLVER_TOKEN;
  if (!url || !agentId || !token) {
    throw new Error(
      'Argus resolver not configured (ARGUS_RESOLVER_URL / ARGUS_AGENT_ID / ARGUS_RESOLVER_TOKEN missing)'
    );
  }
  return new Promise((resolve, reject) => {
    const parsed = new URL(url);
    const body = JSON.stringify({ agent_id: agentId, platform });
    const req = http.request(
      {
        method: 'POST',
        hostname: parsed.hostname,
        port: parsed.port,
        path: parsed.pathname,
        headers: {
          'content-type': 'application/json',
          'content-length': Buffer.byteLength(body),
          'authorization': 'Bearer ' + token,
        },
      },
      (res) => {
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          const text = Buffer.concat(chunks).toString('utf-8');
          if (res.statusCode !== 200) {
            return reject(new Error('Resolver ' + res.statusCode + ': ' + text));
          }
          try {
            const parsedBody = JSON.parse(text);
            if (!parsedBody.device_id) {
              return reject(new Error('Resolver returned no device_id'));
            }
            resolve(parsedBody.device_id);
          } catch (e) {
            reject(e);
          }
        });
      }
    );
    req.on('error', reject);
    req.write(body);
    req.end();
  });
}

(async () => {
  const forwardedArgs = process.argv.slice(2);
  const flag = findDeviceFlag(forwardedArgs);
  const platform = flag ? classifyDevice(flag.value) : null;

  let finalArgs = forwardedArgs;
  if (flag && platform) {
    try {
      const deviceId = await resolveDevice(platform);
      finalArgs = forwardedArgs.slice();
      finalArgs[flag.index] = deviceId;
    } catch (e) {
      process.stderr.write(
        'argus: failed to resolve --device ' + platform + ': ' + e.message + '\\n'
      );
      process.exit(1);
    }
  }

  const child = spawn(
    process.execPath,
    [CONDUCTOR_ENTRY].concat(finalArgs),
    { stdio: 'inherit', env: process.env }
  );
  child.on('exit', (code, signal) => {
    if (signal) {
      process.kill(process.pid, signal);
      return;
    }
    process.exit(code == null ? 1 : code);
  });
  child.on('error', (e) => {
    process.stderr.write('argus: failed to spawn conductor: ' + e.message + '\\n');
    process.exit(1);
  });
})();
`;

/** Write the shim into `<dir>/bin/conductor` (chmod +x). */
export function writeShim(installDir: string): void {
  const binDir = path.join(installDir, "bin");
  mkdirSync(binDir, { recursive: true });
  const binPath = path.join(binDir, "conductor");
  writeFileSync(binPath, SHIM_SCRIPT);
  chmodSync(binPath, 0o755);
}

/**
 * npm args to install `@houwert/conductor@<version>` as a self-contained flat
 * tree under `installDir`. `--ignore-scripts` skips conductor's postinstall
 * (Claude-plugin registration); `--no-package-lock` avoids writing a lockfile.
 */
export function registryInstallArgs(
  version: string,
  installDir: string,
): string[] {
  return [
    "install",
    `${CONDUCTOR_PACKAGE}@${version}`,
    "--prefix",
    installDir,
    "--ignore-scripts",
    "--no-package-lock",
  ];
}

/** Path to the shim binary inside an install tree. */
export function shimBinPath(installDir: string): string {
  return path.join(installDir, "bin", "conductor");
}
