/**
 * Installs @houwert/conductor into `native/conductor/` as a self-contained
 * directory that electron-builder can bundle as an extraResource.
 *
 * Uses `npm install` (not pnpm) to create a flat node_modules layout with all
 * transitive dependencies resolved — no pnpm virtual store gymnastics needed.
 *
 * Run via: tsx scripts/prepare-conductor.ts
 * Also runs as part of `postinstall` alongside fetch-scrcpy-server.ts.
 *
 * The `native/conductor/` directory is gitignored (like `native/scrcpy-server/`).
 *
 * ## Local development against an unpublished conductor
 *
 * Set `CONDUCTOR_LOCAL` to a path (absolute, or relative to this repo root)
 * pointing at a local conductor CLI package directory — typically
 * `../conductor/packages/cli` when the two repos are siblings. The local
 * package will be installed via `npm install <dir>` so all transitive deps
 * resolve normally. Local-mode installs bypass the version cache so rebuilds
 * are always picked up.
 */

import { execFileSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  readFileSync,
  writeFileSync,
  mkdirSync,
  rmSync,
} from "node:fs";
import path from "node:path";
import { log } from "../app/lib/logger";

// ---------------------------------------------------------------------------
// Configuration — bump this when upgrading conductor
// ---------------------------------------------------------------------------

const CONDUCTOR_VERSION = "0.15.0";

// ---------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "native", "conductor");
const VERSION_FILE = path.join(OUT, ".version");
const BIN_DIR = path.join(OUT, "bin");
const BIN_PATH = path.join(BIN_DIR, "conductor");

// ---------------------------------------------------------------------------
// Shim generation
// ---------------------------------------------------------------------------

/**
 * Build the conductor shim. It resolves the real conductor entry point
 * relative to its own directory (via `__dirname`), so the same shim works
 * both in `native/conductor/bin/` (dev) and `<resourcesPath>/conductor/bin/`
 * (packaged) without rewriting.
 *
 * The shim also handles Argus-specific `--device ios|web` placeholders by
 * calling the MCP resolver to acquire a runtime on demand. See the
 * conductor.ts docstring for the full story.
 */
const SHIM_SCRIPT = `#!/usr/bin/env node
/* eslint-disable */
// Auto-generated by scripts/prepare-conductor.ts. Do not edit manually.
'use strict';

const path = require('path');
const { spawn } = require('child_process');
const http = require('http');

const CONDUCTOR_ENTRY = path.join(
  __dirname,
  '..',
  'node_modules',
  '@houwert',
  'conductor',
  'dist',
  'index.js',
);

function findDeviceFlag(argv) {
  for (let i = 0; i < argv.length - 1; i++) {
    if (argv[i] === '--device') {
      return { index: i + 1, value: argv[i + 1] };
    }
  }
  return null;
}

function classifyDevice(value) {
  if (!value) return null;
  if (value === 'web' || value === 'web:chromium') return 'web';
  if (value === 'ios') return 'ios';
  return null; // Already a concrete device ID — pass through.
}

function resolveDevice(platform) {
  const url = process.env.ARGUS_RESOLVER_URL;
  const agentId = process.env.ARGUS_AGENT_ID;
  const token = process.env.ARGUS_RESOLVER_TOKEN;
  if (!url || !agentId || !token) {
    throw new Error(
      'Argus resolver not configured (ARGUS_RESOLVER_URL / ARGUS_AGENT_ID / ARGUS_RESOLVER_TOKEN missing)'
    );
  }
  return new Promise((resolve, reject) => {
    const parsed = new URL(url);
    const body = JSON.stringify({ agent_id: agentId, platform });
    const req = http.request(
      {
        method: 'POST',
        hostname: parsed.hostname,
        port: parsed.port,
        path: parsed.pathname,
        headers: {
          'content-type': 'application/json',
          'content-length': Buffer.byteLength(body),
          'authorization': 'Bearer ' + token,
        },
      },
      (res) => {
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () => {
          const text = Buffer.concat(chunks).toString('utf-8');
          if (res.statusCode !== 200) {
            return reject(new Error('Resolver ' + res.statusCode + ': ' + text));
          }
          try {
            const parsedBody = JSON.parse(text);
            if (!parsedBody.device_id) {
              return reject(new Error('Resolver returned no device_id'));
            }
            resolve(parsedBody.device_id);
          } catch (e) {
            reject(e);
          }
        });
      }
    );
    req.on('error', reject);
    req.write(body);
    req.end();
  });
}

(async () => {
  const forwardedArgs = process.argv.slice(2);
  const flag = findDeviceFlag(forwardedArgs);
  const platform = flag ? classifyDevice(flag.value) : null;

  let finalArgs = forwardedArgs;
  if (flag && platform) {
    try {
      const deviceId = await resolveDevice(platform);
      finalArgs = forwardedArgs.slice();
      finalArgs[flag.index] = deviceId;
    } catch (e) {
      process.stderr.write(
        'argus: failed to resolve --device ' + platform + ': ' + e.message + '\\n'
      );
      process.exit(1);
    }
  }

  const child = spawn(
    process.execPath,
    [CONDUCTOR_ENTRY].concat(finalArgs),
    { stdio: 'inherit', env: process.env }
  );
  child.on('exit', (code, signal) => {
    if (signal) {
      process.kill(process.pid, signal);
      return;
    }
    process.exit(code == null ? 1 : code);
  });
  child.on('error', (e) => {
    process.stderr.write('argus: failed to spawn conductor: ' + e.message + '\\n');
    process.exit(1);
  });
})();
`;

function writeShim(): void {
  mkdirSync(BIN_DIR, { recursive: true });
  writeFileSync(BIN_PATH, SHIM_SCRIPT);
  chmodSync(BIN_PATH, 0o755);
  log(`[prepare-conductor] Wrote conductor shim to ${BIN_PATH}`);
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

function resolveLocalPath(raw: string): string {
  const expanded = raw.startsWith("~")
    ? path.join(process.env.HOME ?? "", raw.slice(1))
    : raw;
  const resolved = path.isAbsolute(expanded)
    ? expanded
    : path.resolve(ROOT, expanded);
  if (!existsSync(path.join(resolved, "package.json"))) {
    throw new Error(`CONDUCTOR_LOCAL path has no package.json: ${resolved}`);
  }

  return resolved;
}

function installFromRegistry(): void {
  if (existsSync(VERSION_FILE)) {
    const existing = readFileSync(VERSION_FILE, "utf-8").trim();
    if (existing === CONDUCTOR_VERSION) {
      log(
        `[prepare-conductor] native/conductor/ already at v${CONDUCTOR_VERSION}, skipping install`,
      );
      writeShim();

      return;
    }
  }

  log(
    `[prepare-conductor] Installing conductor v${CONDUCTOR_VERSION} from registry into native/conductor/...`,
  );

  mkdirSync(OUT, { recursive: true });

  // Use npm to create a self-contained install with flat node_modules.
  // --ignore-scripts: skip conductor's postinstall (which registers as Claude plugin).
  // --no-package-lock: don't write a lockfile into native/conductor/.
  // --prefix: install into our target directory.
  execFileSync(
    "npm",
    [
      "install",
      `@houwert/conductor@${CONDUCTOR_VERSION}`,
      "--prefix",
      OUT,
      "--ignore-scripts",
      "--no-package-lock",
    ],
    {
      stdio: "inherit",
      cwd: ROOT,
      timeout: 60_000,
    },
  );

  writeFileSync(VERSION_FILE, CONDUCTOR_VERSION);
  writeShim();

  log(
    `[prepare-conductor] Done — native/conductor/ ready (v${CONDUCTOR_VERSION})`,
  );
}

function installFromLocal(sourceDir: string): void {
  log(`[prepare-conductor] Installing conductor from local path: ${sourceDir}`);

  mkdirSync(OUT, { recursive: true });

  // `npm install <dir>` copies the package into OUT/node_modules/@houwert/conductor
  // and resolves its dependencies flatly, just like the registry path — but it
  // skips the tarball fetch. `file:` specifiers in npm install from a directory
  // run the package's own `prepare` script (good: ensures `dist/` is built).
  execFileSync(
    "npm",
    [
      "install",
      sourceDir,
      "--prefix",
      OUT,
      "--ignore-scripts",
      "--no-package-lock",
      "--install-links=true", // copy instead of symlink so electron-builder bundles real files
    ],
    {
      stdio: "inherit",
      cwd: ROOT,
      timeout: 120_000,
    },
  );

  // Drop the version marker — local builds aren't version-locked, so the next
  // run should always reinstall to pick up source changes.
  rmSync(VERSION_FILE, { force: true });
  writeShim();

  log(
    `[prepare-conductor] Done — native/conductor/ ready (local: ${sourceDir})`,
  );
}

function main(): void {
  const local = process.env.CONDUCTOR_LOCAL?.trim();
  if (local) {
    installFromLocal(resolveLocalPath(local));

    return;
  }

  installFromRegistry();
}

main();
